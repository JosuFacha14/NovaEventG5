CREATE PROCEDURE SP_PA_SELECT(
    IN  pv_accion          VARCHAR(255)
   ,IN  pi_cod_persona     BIGINT
   ,IN  pi_cod_telefono    BIGINT
   ,IN  pi_cod_rel_pertel  BIGINT
   ,IN  pi_cod_correo      BIGINT
   ,IN  pi_cod_rel_percor  BIGINT
   ,IN  pi_cod_tipo_usr    BIGINT
   ,IN  pi_cod_usuario     BIGINT
   ,IN  pi_cod_tipo_cli    BIGINT
   ,IN  pi_cod_cliente     BIGINT
   ,IN  pi_cod_empleado    BIGINT
   ,IN  pi_cod_proveedor   BIGINT
)
BEGIN

    START TRANSACTION;

    IF pv_accion = 'SEL_PA_PERSONAS' THEN

        SELECT
             COD_PERSONA
            ,DNI
            ,PRIMER_NOMBRE
            ,SEGUNDO_NOMBRE
            ,APELLIDO
            ,SEXO
            ,EST_CIVIL
            ,EDAD
            ,TIP_PERSONA
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_PERSONAS
        WHERE
            (pi_cod_persona IS NULL OR COD_PERSONA = pi_cod_persona);

    ELSEIF pv_accion = 'SEL_PA_TELEFONOS' THEN

        SELECT
             COD_TELEFONO
            ,NUM_AREA
            ,NUM_TELEFONO
