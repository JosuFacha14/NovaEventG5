DELIMITER $$
CREATE PROCEDURE SP_AUTH_SELECT_USUARIO_BY_ID(
    IN pi_cod_usuario BIGINT
)
BEGIN
 
    SELECT
         u.COD_USUARIO
        ,u.COD_PERSONA
        ,u.COD_TIPO_USR
        ,u.NOMBRE
        ,u.IND_USR
        ,u.IND_PRIMER_ING
        ,p.PRIMER_NOMBRE
        ,p.SEGUNDO_NOMBRE
        ,p.APELLIDO
        ,tu.NOM_TIPO
    FROM USUARIOS u
    INNER JOIN PA_PERSONAS p       ON p.COD_PERSONA  = u.COD_PERSONA
    INNER JOIN PA_TIPO_USUARIOS tu ON tu.COD_TIPO_USR = u.COD_TIPO_USR
    WHERE u.COD_USUARIO = pi_cod_usuario;
 
END$$
DELIMITER ;
 