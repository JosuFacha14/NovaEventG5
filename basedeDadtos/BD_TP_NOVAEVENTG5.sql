            COD_ESPA_OCUP = pi_cod_espa_ocup;
    ELSEIF pv_accion = 'UPD_RE_SOFT_DELETE_ESPACIO' THEN
        UPDATE RE_ESPACIO
        SET
            IND_ESTADO = pv_ind_estado
        WHERE
            COD_ESPACIO = pi_cod_espacio;
    ELSEIF pv_accion = 'UPD_RE_SOFT_DELETE_RESERVACION' THEN
        UPDATE RE_RESERVACION
