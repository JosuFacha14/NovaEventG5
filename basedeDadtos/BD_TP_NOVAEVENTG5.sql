            ,DES_TIPO
        FROM
            PA_TIPO_USUARIOS
        WHERE
            (pi_cod_tipo_usr IS NULL OR COD_TIPO_USR = pi_cod_tipo_usr);

    ELSEIF pv_accion = 'SEL_USUARIOS' THEN

        SELECT
             COD_USUARIO
            ,COD_PERSONA
            ,COD_TIPO_USR
            ,NOMBRE
            ,TOKEN
            ,IND_USR
            ,IND_PRIMER_ING
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            USUARIOS
        WHERE
            (pi_cod_usuario  IS NULL OR COD_USUARIO  = pi_cod_usuario)
        AND (pi_cod_persona  IS NULL OR COD_PERSONA  = pi_cod_persona)
        AND (pi_cod_tipo_usr IS NULL OR COD_TIPO_USR = pi_cod_tipo_usr);

    ELSEIF pv_accion = 'SEL_PA_TIPO_CLIENTES' THEN

        SELECT
             COD_TIPO_CLI
            ,NOM_TIPO_CLI
            ,DES_TIPO_CLI
            ,IND_TIPO_CLI
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_TIPO_CLIENTES
        WHERE
            (pi_cod_tipo_cli IS NULL OR COD_TIPO_CLI = pi_cod_tipo_cli);

    ELSEIF pv_accion = 'SEL_PA_CLIENTES' THEN

        SELECT
             COD_CLIENTE
            ,COD_PERSONA
            ,COD_TIPO_CLI
            ,NOM_EMPRESA
            ,IND_CLIENTE
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_CLIENTES
        WHERE
            (pi_cod_cliente  IS NULL OR COD_CLIENTE  = pi_cod_cliente)
        AND (pi_cod_persona  IS NULL OR COD_PERSONA  = pi_cod_persona)
        AND (pi_cod_tipo_cli IS NULL OR COD_TIPO_CLI = pi_cod_tipo_cli);

    ELSEIF pv_accion = 'SEL_PA_EMPLEADOS' THEN

        SELECT
             COD_EMPLEADO
            ,COD_PERSONA
            ,CARGO
            ,FEC_CONTRATACION
            ,SALARIO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_EMPLEADOS
        WHERE
            (pi_cod_empleado IS NULL OR COD_EMPLEADO = pi_cod_empleado)
        AND (pi_cod_persona  IS NULL OR COD_PERSONA  = pi_cod_persona);

    ELSEIF pv_accion = 'SEL_PA_PROVEEDORES' THEN

        SELECT
             COD_PROVEEDOR
            ,COD_PERSONA
            ,EMPRESA
            ,CATEGORIA_SERVICIO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_PROVEEDORES
        WHERE
            (pi_cod_proveedor IS NULL OR COD_PROVEEDOR = pi_cod_proveedor)
        AND (pi_cod_persona   IS NULL OR COD_PERSONA   = pi_cod_persona);

    END IF;

