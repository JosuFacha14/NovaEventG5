-- FILTRADO POR IFS ANIDADOS QUE COMPARAN PV ACCION

DELIMITER $$
CREATE PROCEDURE SP_INSERT_VENTAS(
    IN PV_ACCION VARCHAR(50),

    IN PI_COD_CATEGORIA BIGINT,
    IN PI_COD_CICLO_EVENTO INT,
    IN PI_COD_RESERVACION INT,
    IN PI_COD_EVENTO BIGINT,
    IN PI_COD_BOLETO BIGINT,
    IN PI_COD_CLIENTE BIGINT,
    IN PI_COD_VENTA BIGINT,

    IN PV_NOM_CATEGORIA VARCHAR(100),
    IN PV_DES_CATEGORIA TEXT,

    IN PV_NOM_CICLO VARCHAR(100),
    IN PV_DES_CICLO VARCHAR(255),
    IN PV_USR_INGRESO VARCHAR(255),

    IN PV_NOM_EVENTO VARCHAR(150),
    IN PV_DES_EVENTO TEXT,
    IN PD_FEC_EVENTO DATE,
    IN PT_HOR_EVENTO TIME,
    IN PV_DES_LUGAR VARCHAR(150),
    IN PI_NUM_CAPACIDAD INT,
    IN PV_IND_ESTADO ENUM('ACTIVO','CANCELADO','FINALIZADO'),

    IN PV_TIP_BOLETO ENUM('VIP','GENERAL','PREFERENCIAL','BACKSTAGE'),
    IN PN_MON_PRECIO DECIMAL(10,2),
    IN PI_NUM_DISPONIBLE INT,
    IN PV_DES_BOLETO TEXT,

    IN PN_MON_TOTAL DECIMAL(10,2),
    IN PV_METODO_PAGO ENUM('EFECTIVO','TARJETA','TRANSFERENCIA'),
    IN PV_ESTADO_VENTA ENUM('PAGADA','PENDIENTE','CANCELADA'),

    IN PI_CANTIDAD INT,
    IN PN_PRECIO_UNIT DECIMAL(10,2),
    IN PN_SUBTOTAL DECIMAL(10,2),

    IN PN_MON_PAGO DECIMAL(10,2),
    IN PV_REFERENCIA VARCHAR(100),
    IN PV_ESTADO_PAGO ENUM('APROBADO','PENDIENTE','RECHAZADO')
)
BEGIN
START TRANSACTION;

IF PV_ACCION='INS_CATEGORIA' THEN

    INSERT INTO VE_CATEGORIA_EVENTOS
    (
        NOM_CATEGORIA,
        DES_CATEGORIA
    )
    VALUES
    (
        PV_NOM_CATEGORIA,
        PV_DES_CATEGORIA
    );

ELSEIF PV_ACCION='INS_CICLO' THEN

    INSERT INTO VE_CICLO_EVENTO
    (
        NOM_CICLO,
        DES_CICLO,
        USR_INGRESO
    )
    VALUES
    (
        PV_NOM_CICLO,
        PV_DES_CICLO,
        PV_USR_INGRESO
    );

ELSEIF PV_ACCION='INS_EVENTO' THEN

    INSERT INTO VE_EVENTOS
    (
        COD_CATEGORIA,
        COD_CICLO_EVENTO,
        COD_RESERVACION,
        NOM_EVENTO,
        DES_EVENTO,
        FEC_EVENTO,
        HOR_EVENTO,
        DES_LUGAR,
        NUM_CAPACIDAD,
        IND_ESTADO
    )
    VALUES
    (
        PI_COD_CATEGORIA,
        PI_COD_CICLO_EVENTO,
        PI_COD_RESERVACION,
        PV_NOM_EVENTO,
        PV_DES_EVENTO,
        PD_FEC_EVENTO,
        PT_HOR_EVENTO,
        PV_DES_LUGAR,
        PI_NUM_CAPACIDAD,
        PV_IND_ESTADO
    );

ELSEIF PV_ACCION='INS_BOLETO' THEN

    INSERT INTO VE_BOLETOS
    (
        COD_EVENTO,
        TIP_BOLETO,
        MON_PRECIO,
        NUM_DISPONIBLE,
        DES_BOLETO
    )
    VALUES
    (
        PI_COD_EVENTO,
        PV_TIP_BOLETO,
        PN_MON_PRECIO,
        PI_NUM_DISPONIBLE,
        PV_DES_BOLETO
    );

ELSEIF PV_ACCION='INS_VENTA' THEN

    INSERT INTO VE_VENTAS
    (
        COD_CLIENTE,
        MON_TOTAL,
        IND_METODO_PAGO,
        IND_ESTADO_VENTA
    )
    VALUES
    (
        PI_COD_CLIENTE,
        PN_MON_TOTAL,
        PV_METODO_PAGO,
        PV_ESTADO_VENTA
    );

ELSEIF PV_ACCION='INS_DETALLE' THEN

    INSERT INTO VE_DETALLE_VENTAS
    (
        COD_VENTA,
        COD_BOLETO,
        NUM_CANTIDAD,
        MON_PRECIO_UNIT,
        MON_SUBTOTAL
    )
    VALUES
    (
        PI_COD_VENTA,
        PI_COD_BOLETO,
        PI_CANTIDAD,
        PN_PRECIO_UNIT,
        PN_SUBTOTAL
    );

ELSEIF PV_ACCION='INS_PAGO' THEN

    INSERT INTO VE_PAGOS
    (
        COD_VENTA,
        MON_PAGO,
        COD_REFERENCIA,
        IND_ESTADO_PAGO
    )
    VALUES
    (
        PI_COD_VENTA,
        PN_MON_PAGO,
        PV_REFERENCIA,
        PV_ESTADO_PAGO
    );

END IF;
COMMIT;
END$$
