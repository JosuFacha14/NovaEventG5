        SET
			COD_ESPACIO  = pi_cod_espacio,
            COD_CLIENTE  = pi_cod_cliente,
            COD_EMPLEADO = pi_cod_empleado,
            FEC_INICIO = IFNULL(pv_fec_inicio, NOW()),
            FEC_FIN      = pv_fec_fin,
            IND_ESTADO   = pv_ind_estado,
            DES_NOTAS    = pv_des_notas
        WHERE
            COD_RESERVACION = pi_cod_reservacion;
    ELSEIF pv_accion = 'UPD_RE_ESPACIO_OCUPADO' THEN
