            TOKEN           = pv_token_nuevo,
            IND_PRIMER_ING  = '0',
            USR_INGRESO     = pv_usr_ingreso,
            FEC_INGRESO     = NOW()
        WHERE COD_USUARIO = pi_cod_usuario;
    ELSE
        UPDATE USUARIOS
        SET CLAVE          = pv_clave_nueva,
            IND_PRIMER_ING  = '0',
            USR_INGRESO     = pv_usr_ingreso,
            FEC_INGRESO     = NOW()
        WHERE COD_USUARIO = pi_cod_usuario;
    END IF;
 
    COMMIT;
 
END$$
DELIMITER ;
 

