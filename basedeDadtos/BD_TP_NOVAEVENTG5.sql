CREATE PROCEDURE SP_SELECT_VENTAS(
    IN PV_ACCION VARCHAR(50)
)
BEGIN

    IF PV_ACCION = 'SEL_CATEGORIA' THEN

        SELECT *
        FROM VE_CATEGORIA_EVENTOS
        WHERE IND_ACTIVO = '1';

    ELSEIF PV_ACCION = 'SEL_CICLO' THEN

        SELECT *
        FROM VE_CICLO_EVENTO
        WHERE IND_ACTIVO = '1';

    ELSEIF PV_ACCION = 'SEL_EVENTO' THEN

        SELECT
             E.COD_EVENTO
            ,E.NOM_EVENTO
            ,C.NOM_CATEGORIA
            ,CE.NOM_CICLO
            ,E.FEC_EVENTO
            ,E.HOR_EVENTO
            ,E.DES_LUGAR
            ,E.IND_ESTADO
        FROM VE_EVENTOS E
        INNER JOIN VE_CATEGORIA_EVENTOS C
            ON E.COD_CATEGORIA = C.COD_CATEGORIA
        INNER JOIN VE_CICLO_EVENTO CE
            ON E.COD_CICLO_EVENTO = CE.COD_CICLO_EVENTO
        WHERE E.IND_ACTIVO = '1'
          AND C.IND_ACTIVO = '1'
          AND CE.IND_ACTIVO = '1';

    ELSEIF PV_ACCION = 'SEL_BOLETO' THEN

        SELECT *
        FROM VE_BOLETOS
        WHERE IND_ACTIVO = '1';

    ELSEIF PV_ACCION = 'SEL_VENTA' THEN

        SELECT *
        FROM VE_VENTAS
        WHERE IND_ACTIVO = '1';

    ELSEIF PV_ACCION = 'SEL_DETALLE' THEN

        SELECT *
        FROM VE_DETALLE_VENTAS
        WHERE IND_ACTIVO = '1';

    ELSEIF PV_ACCION = 'SEL_PAGO' THEN

        SELECT *
        FROM VE_PAGOS
        WHERE IND_ACTIVO = '1';

    END IF;

END$$
