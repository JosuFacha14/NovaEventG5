CREATE PROCEDURE SP_AUTH_LOGIN(
    IN pv_nombre_usr VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
)
BEGIN

    SELECT
         u.COD_USUARIO
        ,u.COD_PERSONA
        ,u.COD_TIPO_USR
        ,u.NOMBRE
        ,u.CLAVE
        ,u.IND_USR
        ,u.IND_PRIMER_ING
        ,p.PRIMER_NOMBRE
        ,p.SEGUNDO_NOMBRE
        ,p.APELLIDO
        ,tu.NOM_TIPO
    FROM USUARIOS u
    INNER JOIN PA_PERSONAS p       ON p.COD_PERSONA  = u.COD_PERSONA
    INNER JOIN PA_TIPO_USUARIOS tu ON tu.COD_TIPO_USR = u.COD_TIPO_USR
    WHERE u.NOMBRE = pv_nombre_usr
    LIMIT 1;

END$$
