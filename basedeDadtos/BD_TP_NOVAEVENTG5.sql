CREATE PROCEDURE SP_UPDATE_VENTAS
(
    IN PV_ACCION             VARCHAR(50),
    IN PI_COD_CATEGORIA      BIGINT,
    IN PV_NOM_CATEGORIA      VARCHAR(100),
    IN PV_DES_CATEGORIA      TEXT,
    IN PI_COD_CICLO_EVENTO   INT,
    IN PV_NOM_CICLO          VARCHAR(100),
    IN PV_DES_CICLO          VARCHAR(255),
    IN PV_IND_ACTIVO_CICLO   ENUM('1','0'),
    IN PI_COD_EVENTO         BIGINT,
    IN PI_COD_RESERVACION    INT,
    IN PV_NOM_EVENTO         VARCHAR(150),
    IN PV_DES_EVENTO         TEXT,
    IN PD_FEC_EVENTO         DATE,
    IN PT_HOR_EVENTO         TIME,
    IN PV_DES_LUGAR          VARCHAR(150),
    IN PI_NUM_CAPACIDAD      INT,
    IN PV_IND_ESTADO_EVENTO  ENUM('ACTIVO','CANCELADO','FINALIZADO'),
    IN PI_COD_BOLETO         BIGINT,
    IN PV_TIP_BOLETO         ENUM('VIP','GENERAL','PREFERENCIAL','BACKSTAGE'),
    IN PM_MON_PRECIO         DECIMAL(10,2),
    IN PI_NUM_DISPONIBLE     INT,
    IN PV_DES_BOLETO         TEXT,
    IN PI_COD_VENTA          BIGINT,
    IN PI_COD_CLIENTE        BIGINT,
    IN PM_MON_TOTAL          DECIMAL(10,2),
    IN PV_IND_METODO_PAGO    ENUM('EFECTIVO','TARJETA','TRANSFERENCIA'),
    IN PV_IND_ESTADO_VENTA   ENUM('PAGADA','PENDIENTE','CANCELADA'),
    IN PI_COD_DETALLE        BIGINT,
    IN PI_NUM_CANTIDAD       INT,
    IN PM_MON_PRECIO_UNIT    DECIMAL(10,2),
    IN PM_MON_SUBTOTAL       DECIMAL(10,2),
    IN PI_COD_PAGO           BIGINT,
    IN PM_MON_PAGO           DECIMAL(10,2),
    IN PV_COD_REFERENCIA     VARCHAR(100),
    IN PV_IND_ESTADO_PAGO    ENUM('APROBADO','PENDIENTE','RECHAZADO'),
    IN PV_IND_ACTIVO         ENUM('1','0')
)
BEGIN
START TRANSACTION;

    IF PV_ACCION='UPD_CATEGORIA' THEN
        UPDATE VE_CATEGORIA_EVENTOS
           SET NOM_CATEGORIA = IFNULL(PV_NOM_CATEGORIA, NOM_CATEGORIA),
               DES_CATEGORIA = IFNULL(PV_DES_CATEGORIA, DES_CATEGORIA),
               IND_ACTIVO    = IFNULL(PV_IND_ACTIVO,    IND_ACTIVO)
         WHERE COD_CATEGORIA = PI_COD_CATEGORIA;

    ELSEIF PV_ACCION='DEL_CATEGORIA' THEN
        UPDATE VE_CATEGORIA_EVENTOS
           SET IND_ACTIVO = '0'
         WHERE COD_CATEGORIA = PI_COD_CATEGORIA;

    ELSEIF PV_ACCION='UPD_CICLO' THEN
        UPDATE VE_CICLO_EVENTO
           SET NOM_CICLO  = IFNULL(PV_NOM_CICLO,        NOM_CICLO),
               DES_CICLO  = IFNULL(PV_DES_CICLO,        DES_CICLO),
               IND_ACTIVO = IFNULL(PV_IND_ACTIVO_CICLO, IND_ACTIVO)
         WHERE COD_CICLO_EVENTO = PI_COD_CICLO_EVENTO;

    ELSEIF PV_ACCION='DEL_CICLO' THEN
        UPDATE VE_CICLO_EVENTO
           SET IND_ACTIVO = '0'
         WHERE COD_CICLO_EVENTO = PI_COD_CICLO_EVENTO;

    ELSEIF PV_ACCION='UPD_EVENTO' THEN
        UPDATE VE_EVENTOS
           SET COD_CATEGORIA    = IFNULL(PI_COD_CATEGORIA,   COD_CATEGORIA),
               COD_CICLO_EVENTO = IFNULL(PI_COD_CICLO_EVENTO,COD_CICLO_EVENTO),
               COD_RESERVACION  = IFNULL(PI_COD_RESERVACION, COD_RESERVACION),
               NOM_EVENTO       = IFNULL(PV_NOM_EVENTO,      NOM_EVENTO),
               DES_EVENTO       = IFNULL(PV_DES_EVENTO,      DES_EVENTO),
               FEC_EVENTO       = IFNULL(PD_FEC_EVENTO,      FEC_EVENTO),
               HOR_EVENTO       = IFNULL(PT_HOR_EVENTO,      HOR_EVENTO),
               DES_LUGAR        = IFNULL(PV_DES_LUGAR,       DES_LUGAR),
               NUM_CAPACIDAD    = IFNULL(PI_NUM_CAPACIDAD,   NUM_CAPACIDAD),
               IND_ESTADO       = IFNULL(PV_IND_ESTADO_EVENTO,IND_ESTADO),
               IND_ACTIVO       = IFNULL(PV_IND_ACTIVO,      IND_ACTIVO)
         WHERE COD_EVENTO = PI_COD_EVENTO;

    ELSEIF PV_ACCION='DEL_EVENTO' THEN
        UPDATE VE_EVENTOS
           SET IND_ACTIVO = '0'
         WHERE COD_EVENTO = PI_COD_EVENTO;

    ELSEIF PV_ACCION='UPD_BOLETO' THEN
        UPDATE VE_BOLETOS
           SET COD_EVENTO     = IFNULL(PI_COD_EVENTO,     COD_EVENTO),
               TIP_BOLETO     = IFNULL(PV_TIP_BOLETO,     TIP_BOLETO),
               MON_PRECIO     = IFNULL(PM_MON_PRECIO,     MON_PRECIO),
               NUM_DISPONIBLE = IFNULL(PI_NUM_DISPONIBLE, NUM_DISPONIBLE),
               DES_BOLETO     = IFNULL(PV_DES_BOLETO,     DES_BOLETO),
               IND_ACTIVO     = IFNULL(PV_IND_ACTIVO,     IND_ACTIVO)
         WHERE COD_BOLETO = PI_COD_BOLETO;

    ELSEIF PV_ACCION='DEL_BOLETO' THEN
        UPDATE VE_BOLETOS
           SET IND_ACTIVO='0'
         WHERE COD_BOLETO = PI_COD_BOLETO;

    ELSEIF PV_ACCION='UPD_VENTA' THEN
        UPDATE VE_VENTAS
           SET COD_CLIENTE      = IFNULL(PI_COD_CLIENTE,     COD_CLIENTE),
               MON_TOTAL        = IFNULL(PM_MON_TOTAL,       MON_TOTAL),
               IND_METODO_PAGO  = IFNULL(PV_IND_METODO_PAGO, IND_METODO_PAGO),
               IND_ESTADO_VENTA = IFNULL(PV_IND_ESTADO_VENTA,IND_ESTADO_VENTA),
               IND_ACTIVO       = IFNULL(PV_IND_ACTIVO,      IND_ACTIVO)
         WHERE COD_VENTA = PI_COD_VENTA;

    ELSEIF PV_ACCION='DEL_VENTA' THEN
        UPDATE VE_VENTAS
           SET IND_ACTIVO='0'
         WHERE COD_VENTA = PI_COD_VENTA;

    ELSEIF PV_ACCION='UPD_DETALLE' THEN
        UPDATE VE_DETALLE_VENTAS
           SET COD_VENTA       = IFNULL(PI_COD_VENTA,       COD_VENTA),
               COD_BOLETO      = IFNULL(PI_COD_BOLETO,      COD_BOLETO),
               NUM_CANTIDAD    = IFNULL(PI_NUM_CANTIDAD,     NUM_CANTIDAD),
               MON_PRECIO_UNIT = IFNULL(PM_MON_PRECIO_UNIT, MON_PRECIO_UNIT),
               MON_SUBTOTAL    = IFNULL(PM_MON_SUBTOTAL,    MON_SUBTOTAL),
               IND_ACTIVO      = IFNULL(PV_IND_ACTIVO,      IND_ACTIVO)
         WHERE COD_DETALLE = PI_COD_DETALLE;

    ELSEIF PV_ACCION='DEL_DETALLE' THEN
        UPDATE VE_DETALLE_VENTAS
           SET IND_ACTIVO='0'
         WHERE COD_DETALLE = PI_COD_DETALLE;

    ELSEIF PV_ACCION='UPD_PAGO' THEN
        UPDATE VE_PAGOS
           SET COD_VENTA       = IFNULL(PI_COD_VENTA,        COD_VENTA),
               MON_PAGO        = IFNULL(PM_MON_PAGO,         MON_PAGO),
               COD_REFERENCIA  = IFNULL(PV_COD_REFERENCIA,   COD_REFERENCIA),
               IND_ESTADO_PAGO = IFNULL(PV_IND_ESTADO_PAGO,  IND_ESTADO_PAGO),
               IND_ACTIVO      = IFNULL(PV_IND_ACTIVO,       IND_ACTIVO)
         WHERE COD_PAGO = PI_COD_PAGO;

    ELSEIF PV_ACCION='DEL_PAGO' THEN
        UPDATE VE_PAGOS
           SET IND_ACTIVO='0'
         WHERE COD_PAGO = PI_COD_PAGO;

    END IF;

COMMIT;
END$$
