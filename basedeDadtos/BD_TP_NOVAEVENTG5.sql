CREATE PROCEDURE SP_RE_UPDATE(
	IN  pv_accion           VARCHAR(255),
	IN  pi_cod_espacio      INT,
	IN  pv_nom_espacio      VARCHAR(100),
	IN  pi_can_capacidad    INT,
	IN  pv_tip_espacio      ENUM('SALON','AUDITORIO','AREA_EXTERIOR','SALA_REUNION'),
	IN  pv_ind_estado       ENUM('DISPONIBLE','MANTENIMIENTO','INACTIVO','PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA'),
	IN  pd_mon_precio_hora  DECIMAL(10,2),
	IN  pi_cod_reservacion  INT,
	IN  pi_cod_cliente      BIGINT,
	IN  pi_cod_empleado     BIGINT,
	IN  pv_fec_inicio       DATETIME,
	IN  pv_fec_fin          DATETIME,
	IN  pv_des_notas        TEXT,
	IN  pi_cod_espa_ocup    INT,
	IN  pv_des_motivo       VARCHAR(200)
)
BEGIN
    START TRANSACTION;
    IF pv_accion = 'UPD_RE_ESPACIO' THEN
        UPDATE RE_ESPACIO
        SET
			NOM_ESPACIO     = pv_nom_espacio,
            CAN_CAPACIDAD   = pi_can_capacidad,
            TIP_ESPACIO     = pv_tip_espacio,
            IND_ESTADO      = pv_ind_estado,
            MON_PRECIO_HORA = pd_mon_precio_hora
        WHERE
            COD_ESPACIO = pi_cod_espacio;
    ELSEIF pv_accion = 'UPD_RE_RESERVACION' THEN
