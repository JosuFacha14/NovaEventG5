CREATE TABLE RE_ESPACIO (
   COD_ESPACIO      INT           AUTO_INCREMENT COMMENT 'Codigo unico del espacio'
  ,NOM_ESPACIO      VARCHAR(100)  NOT NULL       COMMENT 'Nombre descriptivo del espacio'
  ,CAN_CAPACIDAD    INT           NOT NULL       COMMENT 'Capacidad maxima de personas'
  ,TIP_ESPACIO      ENUM('SALON','AUDITORIO','AREA_EXTERIOR','SALA_REUNION') NOT NULL COMMENT 'Tipo de espacio configurado'
  ,IND_ESTADO       ENUM('DISPONIBLE','MANTENIMIENTO','INACTIVO') NOT NULL DEFAULT 'DISPONIBLE' COMMENT 'Estado operativo del espacio'
  ,MON_PRECIO_HORA  DECIMAL(10,2) NOT NULL       COMMENT 'Precio de alquiler por hora'
  
  ,CONSTRAINT PK_REESPACIOO PRIMARY KEY (COD_ESPACIO)
  ,CONSTRAINT CK_RE_REESPACIOO_TIPESPAC CHECK (TIP_ESPACIO IN ('SALON', 'AUDITORIO', 'AREA_EXTERIOR', 'SALA_REUNION'))
  ,CONSTRAINT CK_RE_REESPACIOO_INDESTAD CHECK (IND_ESTADO IN ('DISPONIBLE', 'MANTENIMIENTO', 'INACTIVO'))
) ENGINE=INNODB CHARACTER SET UTF8MB4 COLLATE UTF8MB4_UNICODE_CI;

CREATE TABLE RE_RESERVACION (
   COD_RESERVACION  INT           AUTO_INCREMENT COMMENT 'Codigo de la reservacion'
  ,COD_ESPACIO      INT           NOT NULL       COMMENT 'Codigo del espacio reservado'
  ,COD_CLIENTE      BIGINT        NOT NULL       COMMENT 'Codigo del cliente que reserva'
  ,COD_EMPLEADO     BIGINT        NOT NULL       COMMENT 'Codigo del empleado que gestiona'
  ,FEC_INICIO       DATETIME      NOT NULL       COMMENT 'Fecha y hora de inicio de la reservacion'
  ,FEC_FIN          DATETIME      NOT NULL       COMMENT 'Fecha y hora de fin de la reservacion'
  ,IND_ESTADO       ENUM('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA') NOT NULL DEFAULT 'PENDIENTE' COMMENT 'Estado actual de la reservacion'
  ,DES_NOTAS        TEXT                         COMMENT 'Notas adicionales de la reservacion'
  ,USR_INGRESO      VARCHAR(255)  NOT NULL       COMMENT 'USUARIO QUE INGRESO EL REGISTRO'
  ,FEC_INGRESO      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Fecha en que se ingreso el registro'
  
  ,CONSTRAINT PK_RERESERVACI PRIMARY KEY (COD_RESERVACION)
  ,CONSTRAINT FK_RERESERVACI_REESPACIO FOREIGN KEY (COD_ESPACIO) REFERENCES RE_ESPACIO(COD_ESPACIO)
  ,CONSTRAINT FK_RERESERVACI_PACLIENTES FOREIGN KEY (COD_CLIENTE) REFERENCES PA_CLIENTES(COD_CLIENTE) ON DELETE CASCADE
  ,CONSTRAINT FK_RERESERVACI_PAEMPLEADOS FOREIGN KEY (COD_EMPLEADO) REFERENCES PA_EMPLEADOS(COD_EMPLEADO) ON DELETE CASCADE
) ENGINE=INNODB CHARACTER SET UTF8MB4 COLLATE UTF8MB4_UNICODE_CI;

CREATE TABLE RE_ESPACIO_OCUPADO (
   COD_ESPA_OCUP    INT           AUTO_INCREMENT COMMENT 'Codigo del bloqueo de espacio'
