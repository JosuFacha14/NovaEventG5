 IN PV_CARGO             VARCHAR(100),
 IN PD_FEC_CONTRATACION  DATE,
 IN PN_SALARIO           DECIMAL(10,2),
 IN PV_EMPRESA_PROV      VARCHAR(150),
 IN PV_CATEGORIA_SERV    VARCHAR(100),
 IN PV_USR_INGRESO       VARCHAR(255))
BEGIN
START TRANSACTION;

/* =============================================================================
   UPDATE
   ============================================================================= */
IF PV_ACCION = 'UPDATE' THEN

    
    IF PV_SEGUNDO_NOMBRE IS NULL THEN
      UPDATE PA_PERSONAS
      SET DNI            = IFNULL(PV_DNI, DNI),
          PRIMER_NOMBRE  = IFNULL(PV_PRIMER_NOMBRE, PRIMER_NOMBRE),
          APELLIDO       = IFNULL(PV_APELLIDO, APELLIDO),
          SEXO           = IFNULL(PC_SEXO, SEXO),
          EST_CIVIL      = IFNULL(PC_EST_CIVIL, EST_CIVIL),
          EDAD           = IFNULL(PI_EDAD, EDAD),
          USR_INGRESO    = PV_USR_INGRESO,
          FEC_INGRESO    = NOW()
      WHERE COD_PERSONA  = PI_COD_PERSONA;
    ELSE
      UPDATE PA_PERSONAS
      SET DNI            = IFNULL(PV_DNI, DNI),
          PRIMER_NOMBRE  = IFNULL(PV_PRIMER_NOMBRE, PRIMER_NOMBRE),
          SEGUNDO_NOMBRE = PV_SEGUNDO_NOMBRE,
          APELLIDO       = IFNULL(PV_APELLIDO, APELLIDO),
          SEXO           = IFNULL(PC_SEXO, SEXO),
          EST_CIVIL      = IFNULL(PC_EST_CIVIL, EST_CIVIL),
          EDAD           = IFNULL(PI_EDAD, EDAD),
          USR_INGRESO    = PV_USR_INGRESO,
          FEC_INGRESO    = NOW()
      WHERE COD_PERSONA  = PI_COD_PERSONA;
    END IF;

    
    SELECT @COD_TELCEL :=  t.COD_TELEFONO
                           from REL_PERSONAS_TELEFONOS r, PA_TELEFONOS t
                           where r.COD_TELEFONO = t.COD_TELEFONO
                           and r.COD_PERSONA = PI_COD_PERSONA
                           and t.TIP_TELEFONO = 'C';

    IF PI_NUM_AREA_CEL IS NOT NULL AND PI_NUM_TELEFONO_CEL IS NOT NULL THEN
      UPDATE PA_TELEFONOS
      SET NUM_AREA     = PI_NUM_AREA_CEL,
          NUM_TELEFONO = PI_NUM_TELEFONO_CEL,
          USR_INGRESO  = PV_USR_INGRESO,
          FEC_INGRESO  = NOW()
      WHERE COD_TELEFONO = @COD_TELCEL;
    END IF;

    
    SELECT @COD_TELOFI :=  t.COD_TELEFONO
                           from REL_PERSONAS_TELEFONOS r, PA_TELEFONOS t
                           where r.COD_TELEFONO = t.COD_TELEFONO
                           and r.COD_PERSONA = PI_COD_PERSONA
                           and t.TIP_TELEFONO = 'O';

    IF PI_NUM_AREA_OFI IS NOT NULL AND PI_NUM_TELEFONO_OFI IS NOT NULL THEN
      UPDATE PA_TELEFONOS
      SET NUM_AREA     = PI_NUM_AREA_OFI,
          NUM_TELEFONO = PI_NUM_TELEFONO_OFI,
          USR_INGRESO  = PV_USR_INGRESO,
          FEC_INGRESO  = NOW()
      WHERE COD_TELEFONO = @COD_TELOFI;
    END IF;

    
    SELECT @COD_CORREO :=  c.COD_CORREO
                           from REL_PERSONAS_CORREOS r, PA_CORREOS c
                           where r.COD_CORREO = c.COD_CORREO
                           and r.COD_PERSONA = PI_COD_PERSONA;

    IF PV_USUARIO_CORREO IS NOT NULL AND PV_SERVIDOR_CORREO IS NOT NULL THEN
      UPDATE PA_CORREOS
      SET USUARIO_CORREO  = PV_USUARIO_CORREO,
          SERVIDOR_CORREO = PV_SERVIDOR_CORREO,
          USR_INGRESO     = PV_USR_INGRESO,
          FEC_INGRESO     = NOW()
      WHERE COD_CORREO    = @COD_CORREO;
    END IF;

    
    SELECT @COD_USUARIO :=  u.COD_USUARIO
                            from USUARIOS u
                            where u.COD_PERSONA = PI_COD_PERSONA;

    IF PV_NOMBRE_USR IS NOT NULL THEN
      IF PV_CLAVE IS NOT NULL THEN
        UPDATE USUARIOS
        SET NOMBRE         = PV_NOMBRE_USR,
            CLAVE          = PV_CLAVE,
            TOKEN          = IFNULL(PV_TOKEN, TOKEN),
            IND_USR        = IFNULL(PC_IND_USR, IND_USR),
            IND_PRIMER_ING = IFNULL(PC_IND_PRIMER_ING, IND_PRIMER_ING),
            USR_INGRESO    = PV_USR_INGRESO,
            FEC_INGRESO    = NOW()
        WHERE COD_USUARIO  = @COD_USUARIO;
      ELSE
        UPDATE USUARIOS
        SET NOMBRE         = PV_NOMBRE_USR,
            TOKEN          = IFNULL(PV_TOKEN, TOKEN),
            IND_USR        = IFNULL(PC_IND_USR, IND_USR),
            IND_PRIMER_ING = IFNULL(PC_IND_PRIMER_ING, IND_PRIMER_ING),
            USR_INGRESO    = PV_USR_INGRESO,
            FEC_INGRESO    = NOW()
        WHERE COD_USUARIO  = @COD_USUARIO;
      END IF;
    END IF;


    SELECT @COD_CLIENTE :=  cl.COD_CLIENTE
                            from PA_CLIENTES cl
                            where cl.COD_PERSONA = PI_COD_PERSONA;

    IF PV_NOM_EMPRESA_CLI IS NOT NULL THEN
      UPDATE PA_CLIENTES
      SET NOM_EMPRESA  = PV_NOM_EMPRESA_CLI,
          IND_CLIENTE  = IFNULL(PC_IND_CLIENTE, IND_CLIENTE),
          USR_INGRESO  = PV_USR_INGRESO,
          FEC_INGRESO  = NOW()
      WHERE COD_CLIENTE = @COD_CLIENTE;
    ELSEIF PC_IND_CLIENTE IS NOT NULL THEN
      UPDATE PA_CLIENTES
      SET IND_CLIENTE  = PC_IND_CLIENTE,
          USR_INGRESO  = PV_USR_INGRESO,
          FEC_INGRESO  = NOW()
      WHERE COD_CLIENTE = @COD_CLIENTE;
    END IF;

    
    SELECT @COD_EMPLEADO :=  e.COD_EMPLEADO
                             from PA_EMPLEADOS e
                             where e.COD_PERSONA = PI_COD_PERSONA;

    IF PV_CARGO IS NOT NULL THEN
      UPDATE PA_EMPLEADOS
      SET CARGO            = PV_CARGO,
          FEC_CONTRATACION = IFNULL(PD_FEC_CONTRATACION, FEC_CONTRATACION),
          SALARIO          = IFNULL(PN_SALARIO, SALARIO),
          USR_INGRESO      = PV_USR_INGRESO,
          FEC_INGRESO      = NOW()
      WHERE COD_EMPLEADO   = @COD_EMPLEADO;
    ELSEIF PN_SALARIO IS NOT NULL THEN
      UPDATE PA_EMPLEADOS
      SET SALARIO          = PN_SALARIO,
          FEC_CONTRATACION = IFNULL(PD_FEC_CONTRATACION, FEC_CONTRATACION),
          USR_INGRESO      = PV_USR_INGRESO,
          FEC_INGRESO      = NOW()
      WHERE COD_EMPLEADO   = @COD_EMPLEADO;
    END IF;

    
    SELECT @COD_PROVEEDOR :=  p.COD_PROVEEDOR
                              from PA_PROVEEDORES p
                              where p.COD_PERSONA = PI_COD_PERSONA;

    IF PV_EMPRESA_PROV IS NOT NULL THEN
      UPDATE PA_PROVEEDORES
      SET EMPRESA            = PV_EMPRESA_PROV,
          CATEGORIA_SERVICIO = IFNULL(PV_CATEGORIA_SERV, CATEGORIA_SERVICIO),
          USR_INGRESO        = PV_USR_INGRESO,
          FEC_INGRESO        = NOW()
      WHERE COD_PROVEEDOR    = @COD_PROVEEDOR;
    END IF;

/* =============================================================================
   SOFT DELETE
   ============================================================================= */
ELSEIF PV_ACCION = 'SOFT_DELETE' THEN

    
    UPDATE USUARIOS
    SET IND_USR     = '0',
        USR_INGRESO = PV_USR_INGRESO,
        FEC_INGRESO = NOW()
    WHERE COD_PERSONA = PI_COD_PERSONA;
    

END IF;

COMMIT;
END$$
DELIMITER ;

-- =============================================================================
-- PROCEDIMIENTO DE SELECT MODULO DE PERSONAS
-- FILTRADO POR IFS ANIDADOS
-- =============================================================================

DELIMITER $$
CREATE PROCEDURE SP_PA_SELECT(
    IN  pv_accion          VARCHAR(255)
   ,IN  pi_cod_persona     BIGINT
   ,IN  pi_cod_telefono    BIGINT
   ,IN  pi_cod_rel_pertel  BIGINT
   ,IN  pi_cod_correo      BIGINT
   ,IN  pi_cod_rel_percor  BIGINT
   ,IN  pi_cod_tipo_usr    BIGINT
   ,IN  pi_cod_usuario     BIGINT
   ,IN  pi_cod_tipo_cli    BIGINT
   ,IN  pi_cod_cliente     BIGINT
   ,IN  pi_cod_empleado    BIGINT
   ,IN  pi_cod_proveedor   BIGINT
)
BEGIN

    START TRANSACTION;

    IF pv_accion = 'SEL_PA_PERSONAS' THEN

        SELECT
             COD_PERSONA
            ,DNI
            ,PRIMER_NOMBRE
            ,SEGUNDO_NOMBRE
            ,APELLIDO
            ,SEXO
            ,EST_CIVIL
            ,EDAD
            ,TIP_PERSONA
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_PERSONAS
        WHERE
            (pi_cod_persona IS NULL OR COD_PERSONA = pi_cod_persona);

    ELSEIF pv_accion = 'SEL_PA_TELEFONOS' THEN

        SELECT
             COD_TELEFONO
            ,NUM_AREA
            ,NUM_TELEFONO
            ,TIP_TELEFONO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_TELEFONOS
        WHERE
            (pi_cod_telefono IS NULL OR COD_TELEFONO = pi_cod_telefono);

    ELSEIF pv_accion = 'SEL_REL_PERSONAS_TELEFONOS' THEN

        SELECT
             COD_REL_PERTEL
            ,COD_PERSONA
            ,COD_TELEFONO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            REL_PERSONAS_TELEFONOS
        WHERE
            (pi_cod_rel_pertel IS NULL OR COD_REL_PERTEL = pi_cod_rel_pertel)
        AND (pi_cod_persona    IS NULL OR COD_PERSONA    = pi_cod_persona)
        AND (pi_cod_telefono   IS NULL OR COD_TELEFONO   = pi_cod_telefono);

    ELSEIF pv_accion = 'SEL_PA_CORREOS' THEN

        SELECT
             COD_CORREO
            ,USUARIO_CORREO
            ,SERVIDOR_CORREO
            ,TIP_CORREO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_CORREOS
        WHERE
            (pi_cod_correo IS NULL OR COD_CORREO = pi_cod_correo);

    ELSEIF pv_accion = 'SEL_REL_PERSONAS_CORREOS' THEN

        SELECT
             COD_REL_PERCOR
            ,COD_PERSONA
            ,COD_CORREO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            REL_PERSONAS_CORREOS
        WHERE
            (pi_cod_rel_percor IS NULL OR COD_REL_PERCOR = pi_cod_rel_percor)
        AND (pi_cod_persona    IS NULL OR COD_PERSONA    = pi_cod_persona)
        AND (pi_cod_correo     IS NULL OR COD_CORREO     = pi_cod_correo);

    ELSEIF pv_accion = 'SEL_PA_TIPO_USUARIOS' THEN

        SELECT
             COD_TIPO_USR
            ,NOM_TIPO
            ,DES_TIPO
        FROM
            PA_TIPO_USUARIOS
        WHERE
            (pi_cod_tipo_usr IS NULL OR COD_TIPO_USR = pi_cod_tipo_usr);

    ELSEIF pv_accion = 'SEL_USUARIOS' THEN

        SELECT
             COD_USUARIO
            ,COD_PERSONA
            ,COD_TIPO_USR
            ,NOMBRE
            ,TOKEN
            ,IND_USR
            ,IND_PRIMER_ING
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            USUARIOS
        WHERE
            (pi_cod_usuario IS NULL OR COD_USUARIO = pi_cod_usuario)
        AND (pi_cod_persona IS NULL OR COD_PERSONA = pi_cod_persona);

    ELSEIF pv_accion = 'SEL_PA_TIPO_CLIENTES' THEN

        SELECT
             COD_TIPO_CLI
            ,NOM_TIPO_CLI
            ,DES_TIPO_CLI
            ,IND_TIPO_CLI
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_TIPO_CLIENTES
        WHERE
            (pi_cod_tipo_cli IS NULL OR COD_TIPO_CLI = pi_cod_tipo_cli);

    ELSEIF pv_accion = 'SEL_PA_CLIENTES' THEN

        SELECT
             COD_CLIENTE
            ,COD_PERSONA
            ,COD_TIPO_CLI
            ,NOM_EMPRESA
            ,IND_CLIENTE
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_CLIENTES
        WHERE
            (pi_cod_cliente IS NULL OR COD_CLIENTE = pi_cod_cliente)
        AND (pi_cod_persona IS NULL OR COD_PERSONA = pi_cod_persona);

    ELSEIF pv_accion = 'SEL_PA_EMPLEADOS' THEN

        SELECT
             COD_EMPLEADO
            ,COD_PERSONA
            ,CARGO
            ,FEC_CONTRATACION
            ,SALARIO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_EMPLEADOS
        WHERE
            (pi_cod_empleado IS NULL OR COD_EMPLEADO = pi_cod_empleado)
        AND (pi_cod_persona  IS NULL OR COD_PERSONA  = pi_cod_persona);

    ELSEIF pv_accion = 'SEL_PA_PROVEEDORES' THEN

        SELECT
             COD_PROVEEDOR
            ,COD_PERSONA
            ,EMPRESA
            ,CATEGORIA_SERVICIO
            ,USR_INGRESO
            ,FEC_INGRESO
        FROM
            PA_PROVEEDORES
        WHERE
            (pi_cod_proveedor IS NULL OR COD_PROVEEDOR = pi_cod_proveedor)
        AND (pi_cod_persona   IS NULL OR COD_PERSONA   = pi_cod_persona);

    END IF;

    COMMIT;

END$$
DELIMITER ;
